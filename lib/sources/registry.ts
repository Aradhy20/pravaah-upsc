export function getSourceById(id: string): SourceSpecification | undefined {
  return MASTER_SOURCES.find(s => s.id === id);
}

export function isSourcePermittedForExtraction(sourceId: string): boolean {
  const src = getSourceById(sourceId);
  return !!src?.originalContentStoragePermitted;
}

export function getSourcesByCategory(category: SourceCategory): SourceSpecification[] {
  return MASTER_SOURCES.filter(s => s.category === category);
}
